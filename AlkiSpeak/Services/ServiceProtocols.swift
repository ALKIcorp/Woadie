import Foundation

protocol EngineSupervising: AnyObject {
    var isRunning: Bool { get }
    var processIdentifier: Int32? { get }
    var engineState: EngineState { get }
    var healthSummary: EngineHealthSummary { get }
    var onEngineStateChanged: ((EngineState) -> Void)? { get set }
    var onHealthChanged: ((EngineHealthSummary) -> Void)? { get set }
    var onIssue: ((EngineIssue) -> Void)? { get set }
    func start() throws
    func restart() throws
    func stop()
    func noteRequestStarted(jobID: UUID)
    func noteRequestFinished(jobID: UUID)
    func findListeningPidsOnEnginePort() -> [Int32]
    func terminatePortUsers(_ pids: [Int32]) async
}

protocol SpeechGenerating: AnyObject {
    func checkHealth() async -> Bool
    func fetchVoices() async throws -> [String]
    func synthesize(text: String, voice: String, jobID: UUID?) async throws -> SpeechGenerationResult
}

/// A voice that can use the requests around this one, so a long text split
/// into segments keeps one delivery instead of starting fresh each time.
protocol ContextualSpeechGenerating: SpeechGenerating {
    func synthesize(text: String, voice: String, jobID: UUID?, context: SpeechContext) async throws -> SpeechGenerationResult
}

/// Where a request sits in a longer job.
struct SpeechContext: Hashable {
    var previousText: String?
    var nextText: String?
    /// The previous segment's finished clip, generated by this same voice.
    var previousAudioURL: URL?
    /// The provider's IDs for the requests just before this one, oldest first.
    var previousRequestIDs: [String] = []

    static let none = SpeechContext()

    /// What's safe to hand a voice other than the one that made the previous
    /// audio: the surrounding text only.
    var textOnly: SpeechContext {
        SpeechContext(previousText: previousText, nextText: nextText)
    }
}

struct SpeechGenerationResult: Hashable {
    let audioData: Data
    let latencyMs: Int?
    let charCount: Int?
    /// The provider's ID for this request, when it returns one (ElevenLabs).
    var requestID: String? = nil
}

protocol SpeechQueueing: AnyObject {
    func enqueue(text: String, voiceID: String) -> SpeechJob
    func cancel(jobID: UUID)
}

protocol PlaybackCoordinating: AnyObject {
    var onSnapshotChanged: ((PlaybackTransportSnapshot) -> Void)? { get set }
    var onFinished: (() -> Void)? { get set }
    func prepare(characterCounts: [Int])
    /// Queues a clip and returns its duration in seconds.
    @discardableResult
    func append(audioURL: URL, segmentID: UUID, index: Int) throws -> TimeInterval
    func finishEnqueuing()
    func seek(to globalTime: TimeInterval) -> Bool
    func togglePlayback()
    func stop()
    /// Applies listen-only speed/pitch to the live audio graph. Never rewrites
    /// or re-encodes the generated clip files.
    func applyTuning(_ tuning: PlaybackTuning)
}

struct PlaybackTransportSnapshot {
    var state: PlaybackSnapshot.State
    var currentSegmentID: UUID?
    var elapsedTime: TimeInterval
    var bufferedDuration: TimeInterval
    var totalDuration: TimeInterval
    var fftMagnitudes: [Float]
}

protocol LocalSpeechSynthesizing: AnyObject {
    var voiceOptions: [VoiceOption] { get }
    func refreshVoices()
    func speak(text: String, voiceID: String) throws
    func stop()
}

protocol TelemetryCapturing: AnyObject {
    func capture(engineProcessID: Int32?) -> ResourceSnapshot
}

protocol PerformanceDiagnosticRecording: AnyObject {
    var logURL: URL { get }
    var summaryURL: URL { get }
    func startSession(context: [String: String])
    func recordMarker(phase: PerformanceDiagnosticPhase, message: String, jobID: UUID?, context: [String: String])
    func recordSample(
        phase: PerformanceDiagnosticPhase,
        jobID: UUID?,
        system: SystemResourceSnapshot,
        process: ResourceSnapshot,
        context: [String: String]
    )
    func finishSession(context: [String: String])
}
